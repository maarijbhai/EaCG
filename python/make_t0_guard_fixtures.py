#!/usr/bin/env python3
"""Golden vectors for SheetLayout.guardTimeZero (port of segment.guard_time_zero).

Two real pages, made as sheet.digitise_sheet makes them (3,200 px decode, the
export's own corners and rotation, corner rectification, grid fit): Set C
Crumple 124910 (the desktop reference fires there: the tick scale +8.7%
against the grid), and Crumple 124711 (a good run: it must not fire). For each:
the locate mask (2x2 opening), rows, time zero and its source, the rhythm
locator's time zero less the mask offset, the grid's px/mm, the ticks the
reference found, and the guard's answer. Plus hand cases of the trigger and of
t0_from_ticks.

    python make_t0_guard_fixtures.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import run_t0_guard as R  # noqa: E402
from ecgproto import digitise as dig, gridfit, segment, sheet  # noqa: E402
from make_sheet_port_fixtures import emit_mask, fmt  # noqa: E402

OUT = HERE.parent / "android" / "app" / "src" / "test" / "resources" / "t0_guard_fixtures.txt"
CASES = {"fires": "eacg_sheet_ptbxl40_kit_500hz_300dpi_model_20261015_124910.csv",
         "quiet": "eacg_sheet_ptbxl40_kit_500hz_300dpi_model_20261015_124711.csv"}


def ticks_line(lines, key, tk):
    lines.append(f"{key}.px {fmt(tk.px_per_mm)}")
    lines.append(f"{key}.n {tk.n_found}")
    lines.append(f"{key}.pos " + " ".join(f"{r} {k} {fmt(x)}" for r, k, x in tk.positions))


def main() -> int:
    lines = ["# generated by python/make_t0_guard_fixtures.py -- do not edit",
             f"# golden vectors for SheetLayout.guardTimeZero (T0_GUARD_PCT = {segment.T0_GUARD_PCT})"]
    by_name = {p.name: (s, p, h) for s, p, h in R.runs()}
    for case, name in CASES.items():
        s, p, h = by_name[name]
        photo, cw, _ = R.match_photo(s, p, h)
        img = R.photo_bgr(photo, cw)
        corners = np.array([float(v) for v in h["corners_px"].split()]).reshape(4, 2)
        rect, _ = sheet.rectify(img, corners)
        fit = gridfit.fit_grid(rect, segment.locate_sheet(rect).anchor_px_per_mm)
        rect, _ = gridfit.regularise(img, corners, rect.shape, fit)
        m2 = dig.binarise_trace(rect, open_kernel=segment.LOCATE_OPEN_KERNEL)
        sl = segment.locate_sheet(rect, fit.px_per_mm)
        tk = segment.tick_scale(rect, sl)
        g = segment.guard_time_zero(rect, sl, tk, fit.px_per_mm)
        lines.append(f"# {case}: {name} ({photo.name}, {cw} quarter(s) clockwise)")
        emit_mask(lines, f"{case}.m2", m2)
        lines.append(f"{case}.rows " + " ".join(str(r) for r in sl.rows))
        lines.append(f"{case}.t0 {fmt(sl.t0_x)}")
        lines.append(f"{case}.t0_source {sl.t0_source}")
        lines.append(f"{case}.rhythm_t0 {fmt(sl.rhythm.t0_x - segment.mask_offset_px(segment.LOCATE_OPEN_KERNEL))}")
        lines.append(f"{case}.grid {fmt(fit.px_per_mm)}")
        ticks_line(lines, f"{case}.ticks", tk)
        lines.append(f"{case}.fires {int(g is not None)}")
        if g is not None:
            loc, tk2, info = g
            lines.append(f"{case}.accepted {int(info.accepted)}")
            lines.append(f"{case}.out_t0 {fmt(loc.t0_x)}")
            lines.append(f"{case}.out_t0_source {loc.t0_source}")
            ticks_line(lines, f"{case}.out", tk2)
            lines.append(f"{case}.line {info.line()}")
        print(case, name, "fires" if g is not None else "quiet", g[2].line() if g is not None else "")
    trig = [(10.49, 10.0), (10.51, 10.0), (9.51, 10.0), (9.49, 10.0), (float("nan"), 10.0),
            (float("nan"), float("nan")), (12.0, float("nan")), (9.3132, 9.2106), (10.5629, 9.4578)]
    lines.append(f"trigger.n {len(trig)}")
    for i, (t, gp) in enumerate(trig):
        lines.append(f"trigger.{i} {fmt(t)} {fmt(gp)} {int(segment.t0_guard_fires(t, gp))}")
    t0c = [([(0, 1, 725.0), (1, 2, 1352.0), (2, 3, 2015.0)], 10.0), ([(0, 1, 600.5)], 9.8),
           ([(0, 1, 700.0), (1, 1, 702.0), (0, 2, 1325.0), (1, 2, 1329.0)], 10.0), ([], 10.0)]
    lines.append(f"t0ticks.n {len(t0c)}")
    for i, (pos, gp) in enumerate(t0c):
        lines.append(f"t0ticks.{i}.px {fmt(gp)}")
        lines.append(f"t0ticks.{i}.pos " + " ".join(f"{r} {k} {fmt(x)}" for r, k, x in pos))
        lines.append(f"t0ticks.{i}.t0 {fmt(segment.t0_from_ticks(pos, gp))}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, OUT.stat().st_size // 1024, "KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
