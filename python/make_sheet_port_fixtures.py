#!/usr/bin/env python3
"""Golden vectors for the Kotlin port of the full-sheet path.

`ecgproto/sheet.py` (+ the FR1/FR4/FR7 parts of page.py and segment.py, and
canonical.py) against SheetLayout.kt, SheetCorners.kt and SheetCanonical.kt.
Kept in its own file so regenerating it cannot move a number in the other
port suites.

The input is a REAL photograph, ptbxl40_20260929_05, downscaled to the
phone's 3,200 px decode, run through the reference path. The JVM tests
cannot run OpenCV, so the OpenCV stages' OUTPUTS ship as inputs to the pure
stages that follow:

  corners   the grid region mask (1,200 px scale) -> extremes per side and
            the RANSAC inlier set (LCG-driven, so exact on both sides)
  locate    the rectified page binarised (2x2 opening) -> the four
            rows, the rhythm locator, each row's pulse edge, time zero
  ticks     the separator ticks and the time scale
  segment   cells, bands and the per-row time knots
  rows      each row band after isolate_trace -> the tracked classical trace
  leads     on_sheet_columns + cell_signal -> every lead, 500 Hz
  canonical the tile stitching on a frame both sides define procedurally,
            with a fake model both sides define the same way

Masks are run-length encoded per row, as in photo_port_fixtures.txt.

    python make_sheet_port_fixtures.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

import run_photo as rp  # noqa: E402
import score_kit_photo as skp  # noqa: E402
from ecgproto import canonical, digitise as dig, page, segment, sheet  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "android" / "app" / "src" / "test" / "resources" / "sheet_port_fixtures.txt"
PHOTO = "ptbxl40_20260929_05"
PHONE_MAX_DIM = 3200


def fmt(v) -> str:
    v = float(v)
    return "NaN" if not np.isfinite(v) else repr(v)


def emit_mask(lines, case, mask):
    h, w = mask.shape
    lines.append(f"{case}.shape {h} {w}")
    for r in range(h):
        row = mask[r] > 0
        if not row.any():
            continue
        d = np.diff(np.concatenate(([0], row.astype(np.int8), [0])))
        st, en = np.flatnonzero(d == 1), np.flatnonzero(d == -1)
        lines.append(f"{case}.rle.{r} " + " ".join(f"{s} {e - s}" for s, e in zip(st, en)))


def fake_frame(h, w):
    """Shared with SheetPortFixturesTest: RGB float, (h, w, 3)."""
    y, x = np.mgrid[0:h, 0:w]
    f = np.stack([(x * 3 + y * 7 + c * 11) % 256 for c in range(3)], -1)
    return f.astype(np.float32)


def fake_model(batch, training=False):
    """Shared with SheetPortFixturesTest: a deterministic 'row head'."""
    t = np.asarray(batch, np.float64)[0]
    h, w, _ = t.shape
    j = np.arange(2 * w)
    row = t[:, j // 2, 0].mean(axis=0) + (j % 2) * 0.5
    pres = t[h // 2, j // 2, 1] - 128.0
    return {"row": row[None].astype(np.float32), "presence": pres[None].astype(np.float32)}


def main() -> int:
    lines = ["# generated by python/make_sheet_port_fixtures.py -- do not edit",
             f"# golden vectors for SheetLayout.kt / SheetCorners.kt / SheetCanonical.kt "
             f"from {PHOTO} at {PHONE_MAX_DIM} px"]
    e = skp.load_registry()["photos"][PHOTO]
    photo = rp.read_oriented(skp.PHOTOS / e["file"])
    s = PHONE_MAX_DIM / max(photo.shape[:2])
    photo = cv2.resize(photo, None, fx=s, fy=s, interpolation=cv2.INTER_AREA)
    lines.append(f"photo.shape {photo.shape[0]} {photo.shape[1]}")

    # ---- corners: region -> extremes -> RANSAC ---------------------------
    sf = page.FIND_MAX_DIM / max(photo.shape[:2])
    small = cv2.resize(photo, None, fx=sf, fy=sf, interpolation=cv2.INTER_AREA)
    region, _ = page.sheet_region(small)
    emit_mask(lines, "region", region)
    tol = page.FIND_RANSAC_TOL * max(region.shape)
    lines.append(f"ransac.tol {fmt(tol)}")
    h, w = region.shape
    for side in ("top", "right", "bottom", "left"):
        if side in ("top", "bottom"):
            cols = region.any(axis=0)
            first = region.argmax(axis=0).astype(np.float64)
            last = h - 1 - region[::-1].argmax(axis=0).astype(np.float64)
            vals = first if side == "top" else last
            t = np.flatnonzero(cols).astype(np.float64)
            pts = np.stack([t, vals[cols]], 1)
        else:
            rows_ = region.any(axis=1)
            first = region.argmax(axis=1).astype(np.float64)
            last = w - 1 - region[:, ::-1].argmax(axis=1).astype(np.float64)
            vals = last if side == "right" else first
            t = np.flatnonzero(rows_).astype(np.float64)
            pts = np.stack([vals[rows_], t], 1)
        lines.append(f"extreme.{side}.n {len(pts)}")
        lines.append(f"extreme.{side}.sum {fmt(pts[:, 0].sum())} {fmt(pts[:, 1].sum())}")
        # Re-run the draw loop to expose the inlier mask itself.
        n = len(pts)
        best, best_in, state = None, -1, page.LCG_SEED
        for _ in range(page.FIND_RANSAC_ITERS):
            state = (state * page.LCG_MULT + page.LCG_ADD) & page.LCG_MASK
            i = (state >> 8) % n
            state = (state * page.LCG_MULT + page.LCG_ADD) & page.LCG_MASK
            j = (state >> 8) % n
            if i == j:
                continue
            d = pts[j] - pts[i]
            L = np.hypot(*d)
            if L < 1e-6:
                continue
            nrm = np.array([-d[1], d[0]]) / L
            inl = np.abs((pts - pts[i]) @ nrm) <= tol
            if int(inl.sum()) > best_in:
                best_in, best = int(inl.sum()), inl
        idx = np.flatnonzero(best)
        lines.append(f"ransac.{side}.count {len(idx)}")
        lines.append(f"ransac.{side}.idxsum {int(idx.sum())}")
    fc = page.find_sheet_corners(photo)
    lines.append("corners.coarse " + " ".join(fmt(v) for v in fc.coarse.ravel()))
    lines.append("corners.final " + " ".join(fmt(v) for v in fc.corners.ravel()))
    lines.append(f"corners.refined {int(fc.refined)}")

    # ---- locate, ticks, segment --------------------------------------------
    rect, _ = sheet.rectify(photo, fc.corners)
    # One mask for locate and ticks: both binarise with a 2x2 opening
    # (segment.LOCATE_OPEN_KERNEL, tick_scale's open_kernel).
    assert segment.LOCATE_OPEN_KERNEL == 2
    m2 = dig.binarise_trace(rect, open_kernel=2)
    emit_mask(lines, "m2", m2)
    sl = segment.locate_sheet(rect)
    lines.append("locate.rows " + " ".join(str(r) for r in sl.rows))
    lines.append(f"locate.loc_x1 {sl.rhythm.x1}")
    lines.append(f"locate.loc_t0 {fmt(sl.rhythm.t0_x)}")
    approx = sl.rhythm.recording_width_px / (segment.RECORDING_S * dig.MM_PER_S)
    lines.append(f"locate.approx {fmt(approx)}")
    lines.append("locate.edges " + " ".join(fmt(v) for v in sl.t0_per_row))
    lines.append(f"locate.t0 {fmt(sl.t0_x)}")
    lines.append(f"locate.anchor {fmt(sl.anchor_px_per_mm)}")
    ticks = segment.tick_scale(rect, sl)
    lines.append(f"ticks.px {fmt(ticks.px_per_mm)}")
    lines.append(f"ticks.n {ticks.n_found}")
    lines.append("ticks.pos " + " ".join(f"{r} {k} {fmt(x)}" for r, k, x in ticks.positions))
    lines.append("ticks.rejected " + " ".join(f"{r} {k} {fmt(x)}" for r, k, x in ticks.rejected))
    # segment.reject_tick_outliers on hand-made cases: the measured
    # ptbxl40_20260929_02 boundary, both sides of the threshold, two ticks.
    rcases = [
        (9.5664, [(0, 3, 1926.0), (1, 3, 1926.0), (2, 3, 1873.5), (0, 1, 733.0), (1, 1, 733.5),
                  (2, 1, 731.5)]),
        (10.0, [(0, 2, 1000.0), (1, 2, 1000.0), (2, 2, 1009.9)]),
        (10.0, [(0, 2, 1000.0), (1, 2, 1000.0), (2, 2, 1010.1)]),
        (10.0, [(0, 2, 1000.0), (1, 2, 1000.0), (2, 2, 989.9)]),
        (10.0, [(0, 1, 700.0), (1, 1, 800.0)]),
    ]
    # segment.choose_rows: the shadow photo, a good photo, both sides of the
    # threshold, the fallback.
    ccases = [([115, 365, 651, 996, 1372, 1699], [1685, 36, 78, 72, 86, 291]), ([679, 1012, 1344, 1648], [167, 236, 250, 318]), ([300, 679, 1012, 1344, 1648], [40, 167, 236, 250, 318]),
              ([0, 100, 200, 329, 600], [5, 5, 5, 5, 9]), ([0, 100, 200, 331], [5, 5, 5, 5]),
              ([10, 50, 400, 900, 1000], [9, 1, 8, 7, 6])]
    lines.append(f"choose.n {len(ccases)}")
    for i, (pk, vals) in enumerate(ccases):
        lines.append(f"choose.{i}.peaks " + " ".join(str(x) for x in pk))
        lines.append(f"choose.{i}.values " + " ".join(fmt(float(x)) for x in vals))
        lines.append(f"choose.{i}.rows " + " ".join(str(x) for x in segment.choose_rows(pk, vals)))
    lines.append(f"reject.n {len(rcases)}")
    for i, (pxm, pos) in enumerate(rcases):
        keep, drop = segment.reject_tick_outliers(pos, pxm)
        lines.append(f"reject.{i}.px {fmt(pxm)}")
        lines.append(f"reject.{i}.pos " + " ".join(f"{r} {k} {fmt(x)}" for r, k, x in pos))
        lines.append(f"reject.{i}.drop " + " ".join(str(j) for j in drop))
    layout = segment.segment_leads(rect, sl.as_strip_location(), ticks.px_per_mm, ticks)
    lines.append(f"layout.height {rect.shape[0]}")
    lines.append("layout.bands " + " ".join(f"{a} {b}" for a, b in layout.row_bands))
    for r, (xs, ts) in enumerate(layout.row_knots):
        lines.append(f"layout.knots.{r} " + " ".join(f"{fmt(x)} {fmt(t)}" for x, t in zip(xs, ts)))
    lines.append("layout.cells " + " ".join(f"{c.x0} {c.x1} {c.y0} {c.y1}" for c in layout.cells))

    # ---- classical rows and the leads -------------------------------------
    for r in range(4):
        y0, y1 = layout.row_bands[r]
        rc = [c for c in layout.cells if c.row == r]
        x0 = min(c.x0 for c in rc)
        x1 = min(max(c.x1 for c in rc), rect.shape[1])
        band = segment.isolate_trace(dig.binarise_trace(rect[y0:y1, x0:x1], open_kernel=2))
        emit_mask(lines, f"band{r}", band)
        lines.append(f"band{r}.x0 {x0}")
        pos, xo = segment.trace_row(rect, layout, r, 2)
        assert xo == x0
        lines.append(f"row{r}.pos " + " ".join(fmt(v) for v in pos))
        # As sheet.classical_row_tracer: mask columns are one pixel late.
        grid, g0 = sheet.on_sheet_columns(xo - segment.mask_offset_px(2)
                                          + np.arange(len(pos), dtype=np.float64), pos)
        for c in rc:
            sig = sheet.cell_signal(grid, g0, c, ticks.px_per_mm, ticks.px_per_mm, layout)
            tag = f"{c.name}{'_rh' if c.row == 3 else ''}"
            lines.append(f"lead.{tag} " + " ".join(fmt(v) for v in sig))

    # ---- canonical: stitching, mapping, pad median ------------------------
    fh, fw = 16, canonical.CANON_W
    frame = fake_frame(fh, fw)
    out = canonical.predict_tiled(fake_model, frame, tile_w=1024)
    lines.append(f"tile.shape {fh} {fw}")
    lines.append("tile.row " + " ".join(fmt(v) for v in out["row"]))
    lines.append("tile.pres " + " ".join(fmt(v) for v in out["presence"]))
    cm = canonical.CanonMap(0.6743, -27, 41)
    rr = np.array([10.0, 200.5, np.nan, 383.25])
    pp = np.array([1.0, -0.5, 2.0, 0.25])
    xs, ys = canonical.row_trace_to_source(rr, pp, cm)
    lines.append("map.in " + " ".join(fmt(v) for v in rr))
    lines.append("map.pres " + " ".join(fmt(v) for v in pp))
    lines.append("map.xs " + " ".join(fmt(v) for v in xs))
    lines.append("map.ys " + " ".join(fmt(v) for v in ys))
    rng = np.random.default_rng(5)
    vals = rng.integers(0, 256, 1000).astype(np.uint8)
    for n in (1000, 999):
        v = vals[:n]
        lines.append(f"med.{n}.hist " + " ".join(str(int(c)) for c in np.bincount(v, minlength=256)))
        lines.append(f"med.{n}.want {int(np.asarray(np.median(v)).astype(np.uint8))}")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({OUT.stat().st_size / 1e6:.1f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
