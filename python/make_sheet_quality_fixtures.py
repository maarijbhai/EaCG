#!/usr/bin/env python3
"""Golden vectors for SheetQuality.kt, the port of ecgproto/sheet_quality.py.

Each case is the inputs of `sheet_quality.assess` and the warnings it
returns -- code, severity and affected leads, in order -- plus the verdict.
Messages are not compared (number formatting differs between the
languages; the text is for the user, the codes are the contract). Leads are
short arrays: coverage and peak-to-peak do not depend on length.

Cases cover every warning on both sides of its threshold, the measured
failures (ptbxl40_20260929_02's misplaced tick, the 3x3-opening phone run's
scale), and a clean sheet.

    python make_sheet_quality_fixtures.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from ecgproto import sheet_quality as Q  # noqa: E402

OUT = (Path(__file__).resolve().parents[1] / "android" / "app" / "src" / "test"
       / "resources" / "sheet_quality_fixtures.txt")
PX = 9.5664
NAMES = [n for row in Q.LAYOUT_3X4 for n in row] + ["II_rhythm"]


def ticks(rows_agree: bool = False):
    xs = {1: 733.0, 2: 1328.0, 3: 1926.0}
    return [(r, k, xs[k] + (0.0 if rows_agree else 0.5 * r)) for r in range(3) for k in (1, 2, 3)]


def leads():
    v = 0.6 * np.sin(np.linspace(0, 6, 20))
    return {n: v.copy() for n in NAMES}


def base(**over):
    d = dict(grid_requested=True, grid_used=True, grid_px_per_mm=PX,
             calibration="ticks", px_per_mm=PX, ticks_found=9,
             tick_positions=ticks(), t0_source="pulses", leads=leads(), tick_rejected=[],
             rows=(679, 1012, 1344, 1648))
    d.update(over)
    return d


def cases():
    out = [("clean", base())]
    out.append(("grid_refused", base(grid_used=False, grid_px_per_mm=float("nan"))))
    out.append(("corners_chosen", base(grid_requested=False, grid_used=False,
                                       grid_px_per_mm=float("nan"))))
    out.append(("ticks_6", base(ticks_found=6)))
    out.append(("ticks_5", base(ticks_found=5)))
    out.append(("duration", base(calibration="duration", ticks_found=2, tick_positions=[])))
    for f in (1.0095, 0.9905, 1.0105, 0.9895):
        out.append((f"scale_{f}", base(px_per_mm=PX * f)))
    out.append(("phone_3x3_failure", base(grid_px_per_mm=9.79, px_per_mm=6.5173)))
    t = ticks()
    t[-1] = (2, 3, 1873.5)
    out.append(("ptbxl40_20260929_02_tick", base(tick_positions=t)))
    for off in (0.99, 1.01, -1.01):
        t = ticks(rows_agree=True)
        r, k, x = t[0]
        t[0] = (r, k, x + off * PX)
        out.append((f"tick_off_{off}", base(tick_positions=t)))
    for gap in (1.9, 2.1):
        t = [(r, k, x + (gap * PX if (r, k) == (1, 1) else 0.0))
             for r, k, x in ticks() if not (k == 1 and r == 2)]
        out.append((f"two_ticks_{gap}", base(tick_positions=t, ticks_found=8)))
    t = [x for x in ticks() if (x[0], x[1]) != (2, 3)]
    out.append(("ptbxl40_20260929_02_replaced",
                base(tick_positions=t, ticks_found=8, tick_rejected=[(2, 3, 1873.5)])))
    out.append(("replaced_without_mates",
                base(tick_positions=[x for x in ticks() if x[1] != 2], ticks_found=6,
                     tick_rejected=[(1, 2, 1200.0)])))
    out.append(("rows_shadow_photo", base(rows=(115, 651, 1372, 1699))))
    out.append(("rows_ratio_1.29", base(rows=(0, 100, 200, 329))))
    out.append(("rows_ratio_1.31", base(rows=(0, 100, 200, 331))))
    out.append(("lone_tick", base(tick_positions=[(0, 1, 900.0)], ticks_found=6)))
    out.append(("no_pulse", base(t0_source="rhythm_locator")))
    lv = leads()
    lv["V4"][:5] = np.nan            # 75% traced
    lv["aVL"] = np.full(20, 0.01)    # flat
    lv["V5"][:] = np.nan             # nothing
    lv["V1"] = lv["V1"] * (6.1 / (lv["V1"].max() - lv["V1"].min()))   # 6.1 mV
    lv["V2"][:3] = np.nan            # 85% traced
    out.append(("leads", base(leads=lv)))
    out.append(("everything", base(grid_used=False, grid_px_per_mm=float("nan"),
                                   ticks_found=4, t0_source="rhythm_locator", leads=lv)))
    return out


def fmt(v) -> str:
    return "nan" if not np.isfinite(v) else repr(float(v))


def main() -> int:
    lines = ["# generated by python/make_sheet_quality_fixtures.py -- do not edit",
             "# golden vectors for SheetQuality.kt (ecgproto/sheet_quality.py)",
             f"const.SCALE_DISAGREE_FRACTION {Q.SCALE_DISAGREE_FRACTION!r}",
             f"const.TICK_MATE_MM {Q.TICK_MATE_MM!r}",
             f"const.MIN_TICKS {Q.MIN_TICKS}",
             f"const.MIN_LEAD_COVERAGE {Q.MIN_LEAD_COVERAGE!r}",
             f"const.REJECT_PP_MV {Q.REJECT_PP_MV[0]!r} {Q.REJECT_PP_MV[1]!r}",
             f"const.ROW_SPACING_MAX_RATIO {Q.ROW_SPACING_MAX_RATIO!r}"]
    cs = cases()
    lines.append(f"cases {len(cs)}")
    for i, (name, kw) in enumerate(cs):
        ws = Q.assess(**kw)
        p = f"case.{i}"
        lines.append(f"{p}.name {name}")
        lines.append(f"{p}.flags {int(kw['grid_requested'])} {int(kw['grid_used'])} "
                     f"{kw['calibration']} {kw['ticks_found']} {kw['t0_source']}")
        lines.append(f"{p}.scales {fmt(kw['grid_px_per_mm'])} {fmt(kw['px_per_mm'])}")
        lines.append(f"{p}.ticks " + " ".join(f"{r} {k} {fmt(x)}" for r, k, x in kw["tick_positions"]))
        lines.append(f"{p}.rows " + " ".join(str(y) for y in kw["rows"]))
        lines.append(f"{p}.rejected " + " ".join(f"{r} {k} {fmt(x)}" for r, k, x in kw["tick_rejected"]))
        for n in NAMES:
            lines.append(f"{p}.lead.{n} " + " ".join(fmt(v) for v in kw["leads"][n]))
        lines.append(f"{p}.n {len(ws)}")
        for j, w in enumerate(ws):
            lines.append(f"{p}.w.{j} {w.code} {w.severity} {','.join(w.leads) or '-'}")
        lines.append(f"{p}.verdict {Q.verdict(ws)}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT, len(cs), "cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
