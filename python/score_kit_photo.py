RHYTHM_LEAD = "II"
RECORDING_S = 10.0
FS = 500.0

#: Vertical margin kept around the true rhythm trace in the `known` crop.
#: 4 mm clears the trace's own ink width and anti-aliasing; the crop is
#: also never allowed to reach within 1 mm of the row above.
KNOWN_MARGIN_MM = 4.0

#: How far past the calibration pulse's falling edge the `known` crop
#: starts, in mm. The edge is a line of finite width, anti-aliased on paper
#: and blurred by the lens; half a millimetre clears it at 300 dpi and at
#: the ~20 px/mm of a 24.8 MP frame.
KNOWN_PULSE_CLEARANCE_MM = 0.5


# --------------------------------------------------------------------------
# the target: what was printed, in the sheet's own pixels
# --------------------------------------------------------------------------

class Target:
    """One `make_kit_target.py` output directory, read once."""

    def __init__(self, name: str, root: Path = TARGETS):
        d = root / name
        if not d.exists():
            raise FileNotFoundError(
                f"no kit target {d}; generate it with make_kit_target.py")
        self.name = name
        self.manifest = json.loads((d / f"{name}.json").read_text("utf-8"))
        kit = json.loads((d / f"{name}_kit.json").read_text("utf-8"))
        self.sheet = cv2.imread(str(d / f"{name}.png"), cv2.IMREAD_COLOR)
        self.truth = np.load(d / f"{name}_truth.npy")
        self.ecg_id = int(self.manifest["source"]["ecg_id"])
        self.fs = float(self.manifest["source"]["sampling_rate_hz"])
        self.px_per_mm = float(self.manifest["calibration"]["px_per_mm_nominal"])
        self.width_mm, self.height_mm = self.manifest["page"]["final_mm"]
        h, w = self.sheet.shape[:2]
        # final_mm is rounded to 0.01 mm; the pixel size is exact.
        self.width_mm, self.height_mm = w / self.px_per_mm, h / self.px_per_mm

        off = self.manifest["page"]["plotted_pixels_offset_px"]
        leads = []
        for lead in kit["leads"]:
            p = np.asarray(lead["plotted_pixels"], dtype=np.float64)
            # (row, col) in the kit's original render, NOT (x, y); shifted by
            # the frame strip and the blank-grid crop. See make_kit_target.
            rows, cols = p[:, 0] - off["y"], p[:, 1] - off["x"]
            n = int(lead["end_sample"]) - int(lead["start_sample"])
            leads.append((lead["lead_name"], int(lead["start_sample"]), n,
                          rows, cols))
        # The rhythm strip is the lead printed across all ten seconds.
        full = [l for l in leads if l[2] >= int(RECORDING_S * self.fs) - 1]
        if not full:
            raise ValueError(f"{name}: no full-length lead in the kit sidecar")
        name_, start, n, self.rows, self.cols = full[-1]
        if name_.upper() != RHYTHM_LEAD:
            raise ValueError(f"{name}: rhythm lead is {name_}, expected II")
        self.start_sample = start
        self.n_samples = n
        self.lead_signal = self.truth[:, ptbxl.LEAD_NAMES.index(RHYTHM_LEAD)]
        # Everything plotted in the row above the rhythm strip.
        above = [l for l in leads if l[3].min() < self.rows.min()]
        self.above_max_row = max(l[3].max() for l in above) if above else 0.0

    @property
    def t0_col(self) -> float:
        """Column of recording time zero: the first plotted sample."""
        return float(self.cols.min())

    def known_box(self) -> tuple[int, int, int, int]:
        """The rhythm strip's crop in sheet pixels, from the kit's truth."""
        mm = self.px_per_mm
        h, w = self.sheet.shape[:2]
        y0 = max(self.rows.min() - KNOWN_MARGIN_MM * mm,
                 self.above_max_row + 1.0 * mm)
        y1 = min(h, self.rows.max() + KNOWN_MARGIN_MM * mm)
        x0 = self.t0_col + KNOWN_PULSE_CLEARANCE_MM * mm
        x1 = min(w, self.cols.max() + KNOWN_PULSE_CLEARANCE_MM * mm)
        return int(np.ceil(x0)), int(y0), int(x1), int(y1)

    def truth_row_per_column(self, x0: int, x1: int) -> np.ndarray:
        """Mean plotted row for each sheet column in [x0, x1), NaN if none.

        The column centroid of the ink is the tracer's estimate of exactly
        this -- where the trace sits in that column -- so comparing the two
        measures FR5+FR6 in millimetres with no calibration involved.
        """
        col = np.floor(self.cols + 0.5).astype(int)
        out = np.full(x1 - x0, np.nan)
        keep = (col >= x0) & (col < x1)
        sums = np.bincount(col[keep] - x0, weights=self.rows[keep],
                           minlength=x1 - x0)
        counts = np.bincount(col[keep] - x0, minlength=x1 - x0)
        ok = counts > 0
        out[ok] = sums[ok] / counts[ok]
        return out


