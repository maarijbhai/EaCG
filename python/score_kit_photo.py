def score_signal(sig: np.ndarray, truth: np.ndarray, fs: float,
                 offset_s: float) -> dict:
    """Metrics for `sig`, whose first sample is `offset_s` into `truth`.

    `asis` uses only the offset the geometry implies -- no search. The
    `aligned` figures come from `run_photo.best_alignment`, whose
    time-rescale separates a calibration error (scale != 1) from a tracing
    error (low PCC at the best scale).
    """
    sig = rp.fill_nan(sig)
    k = int(round(offset_s * fs))
    if k >= 0:
        ref, test = truth[k:], sig
    else:
        ref, test = truth, sig[-k:]
    m = evaluate.evaluate_all(ref, test, fs)
    pcc_a, scale, lag, n, at_bound = rp.best_alignment(ref, test)
    return {
        "offset_samples": k,
        "duration_s": round(len(sig) / fs, 4),
        "pcc_asis": round(float(m.pcc), 4),
        "rmse_mv_asis": round(float(m.rmse_mv), 4),
        "snr_db_asis": round(float(m.snr_db), 3),
        "shifted_snr_db_asis": round(float(m.shifted_snr_db), 3),
        "gain_ratio_asis": round(float(m.gain_ratio), 4),
        "n_compared": int(m.n_compared),
        "pcc_aligned": round(float(pcc_a), 4),
        "align_scale_pct": round(100.0 * (scale - 1.0), 3),
        "align_lag_samples": int(lag),
        "align_at_bound": at_bound,
        "align_overlap_s": round(n / fs, 3),
    }


def strip_mask(strip: np.ndarray) -> np.ndarray:
    """FR5 as the scorer runs it: shipped binarisation, then text removed."""
    return segment.isolate_trace(dig.binarise_trace(strip))


def digitise_and_gate(strip: np.ndarray, px_per_mm_x: float,
                      px_per_mm_y: float) -> tuple[dig.DigitiseResult, dict]:
    """The shipped chain from FR5 on, with the calibration supplied."""
    grid = dig.GridEstimate(px_per_mm_x, px_per_mm_y, float("nan"), 0, 0)
    mask = strip_mask(strip)
    res = dig.digitise(strip, fs_out=FS, grid=grid, strict=False,
                       expected_duration_s=RECORDING_S, mask=mask)
    rep = quality.assess(res, mask=mask)
    return res, {
        "coverage": round(float(res.coverage), 4),
        "calibration_ok": bool(res.calibration.ok) if res.calibration else "",
        "gate_verdict": rep.verdict.name,
        "gate_rejections": ";".join(rep.rejections or []),
        "gate_flags": ";".join(rep.flags or []),
    }


def score_known(photo: np.ndarray, corners: np.ndarray, target: Target,
                diag: Path | None) -> dict:
    sheet = warp_to_sheet(photo, corners, target)
    x0, y0, x1, y1 = target.known_box()
    strip = sheet[y0:y1, x0:x1]
    mm = target.px_per_mm

    # FR5+FR6 in millimetres, with no calibration anywhere in the loop.
    mask = strip_mask(strip)
    traced = dig.trace_positions(mask) + y0
    true_rows = target.truth_row_per_column(x0, x1)
    both = np.isfinite(traced) & np.isfinite(true_rows)
    err_mm = (traced[both] - true_rows[both]) / mm

    res, gate = digitise_and_gate(strip, mm, mm)
    offset_s = (x0 - target.t0_col) / (mm * dig.MM_PER_S)
    row = {
        "mode": "known",
        "calibration": "known",
        "px_per_mm_used": round(mm, 4),
        "px_per_mm_true": round(mm, 4),
        "pitch_error_pct": 0.0,
        "crop_px": f"{x0},{y0},{x1},{y1}",
        "ink_pct": round(100.0 * float(mask.mean()), 3),
        "trace_cols_scored": int(both.sum()),
        # Sign: image rows grow downward, so a positive bias is a trace
        # read BELOW the truth.
        "trace_bias_mm": round(float(np.mean(err_mm)), 4) if both.any() else "",
        "trace_rmse_mm": round(float(np.sqrt(np.mean(err_mm ** 2))), 4)
        if both.any() else "",
        "trace_p95_abs_mm": round(float(np.percentile(np.abs(err_mm), 95)), 4)
        if both.any() else "",
    }
    row.update(gate)
    row.update(score_signal(res.signal_mv, target.lead_signal, target.fs,
                            offset_s))
    if diag is not None:
        overlay = strip.copy()
        for x in np.flatnonzero(both):
            cv2.circle(overlay, (int(x), int(round(true_rows[x] - y0))), 1,
                       (255, 160, 0), -1)
            cv2.circle(overlay, (int(x), int(round(traced[x] - y0))), 1,
                       (0, 0, 255), -1)
        cv2.imwrite(str(diag / "known_overlay.png"), overlay)
    return row


def score_pipeline(photo: np.ndarray, corners: np.ndarray, target: Target,
                   diag: Path | None) -> list[dict]:
    rect, geom = rectify(photo, corners)
    true_x = geom["out_w"] / target.width_mm
    true_y = geom["out_h"] / target.height_mm
    base = {
        "mode": "pipeline",
        "rect_w": geom["out_w"],
        "rect_h": geom["out_h"],
        "keystone_h": round(geom["keystone_horizontal"], 4),
        "keystone_v": round(geom["keystone_vertical"], 4),
        "px_per_mm_true": round(true_x, 4),
        "px_per_mm_true_y": round(true_y, 4),
    }

    try:
        loc = segment.locate_rhythm_strip(rect)
    except RuntimeError as exc:
        return [dict(base, calibration="-", error=f"locate: {exc}")]
    lev = segment.level_strip(rect, loc)
    strip = lev.image
    base.update({
        "level_angle_deg": round(lev.angle_deg, 4),
        "level_margin": round(lev.margin, 3),
        "level_applied": lev.applied,
    })

    # How well the locator did, against the kit's box scaled into this frame.
    sx, sy = geom["out_w"] / target.sheet.shape[1], geom["out_h"] / target.sheet.shape[0]
    t0_true = target.t0_col * sx
    base.update({
        "crop_px": ",".join(str(v) for v in loc.box),
        "locate_t0_error_px": round(loc.t0_x - t0_true, 2),
        "locate_pulse_found": loc.pulse_x1 is not None,
        "locate_y_contains_truth": bool(
            loc.y0 <= target.rows.min() * sy and loc.y1 >= target.rows.max() * sy),
    })

    cals = {}
    g = dig.estimate_grid_pitch(rect)
    cals["grid"] = (g.px_per_mm_x, g.px_per_mm_y)
    py0, py1 = paper_band(rect, loc)
    p5 = float("nan")
    if py1 - py0 > 20:
        p5, cv, _ = rp.comb(rp.detrended_projection(
            dig.redness(rect[py0:py1]), axis=0))
    cals["comb"] = (p5 / 5.0, p5 / 5.0)
    anchor = loc.recording_width_px / (RECORDING_S * dig.MM_PER_S)
    # The anchor is horizontal only; nothing on the page anchors vertical
    # scale from outside except the calibration pulse, which is not yet
    # measured (limitation 12). Isotropy is ASSUMED for this row.
    cals["duration"] = (anchor, anchor)

    rows = []
    for name, (px_x, px_y) in cals.items():
        row = dict(base, calibration=name)
        if not (np.isfinite(px_x) and np.isfinite(px_y)) or px_x <= 0:
            row["error"] = "calibration failed (NaN)"
            rows.append(row)
            continue
        row.update({
            "px_per_mm_used": round(float(px_x), 4),
            "px_per_mm_used_y": round(float(px_y), 4),
            "pitch_error_pct": round(100.0 * (px_x / true_x - 1.0), 3),
            "pitch_error_y_pct": round(100.0 * (px_y / true_y - 1.0), 3),
        })
        try:
            res, gate = digitise_and_gate(strip, px_x, px_y)
        except ValueError as exc:
            row["error"] = f"digitise: {exc}"
            rows.append(row)
            continue
        row.update(gate)
        # Where the pipeline believes sample 0 sits: its own t0, its own
        # scale. No truth enters the offset.
        offset_s = (loc.x0 - loc.t0_x) / (px_x * dig.MM_PER_S)
        row.update(score_signal(res.signal_mv, target.lead_signal,
                                target.fs, offset_s))
        rows.append(row)

    if diag is not None:
        view = rect.copy()
        cv2.rectangle(view, (loc.x0, loc.y0), (loc.x1, loc.y1), (0, 200, 0), 6)
        if py1 > py0:
            cv2.rectangle(view, (0, py0), (view.shape[1] - 1, py1),
                          (255, 128, 0), 6)
        cv2.imwrite(str(diag / "pipeline_rect.jpg"),
                    cv2.resize(view, None, fx=0.25, fy=0.25,
                               interpolation=cv2.INTER_AREA))
    return rows


def score_photo_entry(stem: str, entry: dict, photo_dir: Path,
                      target_root: Path, diag_root: Path | None,
                      refine: bool = True,
                      true_corners: np.ndarray | None = None) -> list[dict]:
    path = photo_dir / entry.get("file", f"{stem}.jpg")
    target = Target(entry["target"], target_root)
    photo = rp.read_oriented(path)
    clicked = np.asarray(entry["corners_px"], dtype=np.float32)
    corners = clicked
    refined = {"corner_refine": "off"}
    if refine:
        # The clicks are a starting point, not a measurement: see
        # ecgproto/page.py for why a raw click costs up to a fifth of PCC.
        try:
            r = page.refine_corners(photo, clicked)
            corners = r.corners
            refined = {
                "corner_refine": "on",
                "corner_shift_px_mean": round(float(r.shift_px.mean()), 2),
                "corner_shift_px_max": round(float(r.shift_px.max()), 2),
                "edge_fit_rmse_px_max": round(float(r.edge_rmse_px.max()), 3),
                "edge_inliers_min": int(r.edge_inliers.min()),
            }
        except RuntimeError as exc:
            refined = {"corner_refine": f"failed, clicks used: {exc}"}
    if true_corners is not None:
        refined["corner_error_px_clicked"] = round(float(
            np.hypot(*(clicked - true_corners).T).mean()), 2)
        refined["corner_error_px_used"] = round(float(
            np.hypot(*(corners - true_corners).T).mean()), 2)
    diag = None
    if diag_root is not None:
        diag = diag_root / stem
        diag.mkdir(parents=True, exist_ok=True)
    head = {
        "photo": stem,
        "target": target.name,
        "ecg_id": target.ecg_id,
        "strat_fold": target.manifest["source"]["strat_fold"],
        "megapixels": round(photo.shape[0] * photo.shape[1] / 1e6, 2),
        "corners_clicked": " ".join(f"{x:.1f},{y:.1f}" for x, y in clicked),
        "corners": " ".join(f"{x:.2f},{y:.2f}" for x, y in corners),
        "note": entry.get("note", ""),
        **refined,
    }
    rows = []
    try:
        rows.append(dict(head, **score_known(photo, corners, target, diag)))
    except Exception as exc:
        rows.append(dict(head, mode="known", error=f"{type(exc).__name__}: {exc}"))
    try:
        rows += [dict(head, **r) for r in score_pipeline(photo, corners,
                                                         target, diag)]
    except Exception as exc:
        rows.append(dict(head, mode="pipeline",
                         error=f"{type(exc).__name__}: {exc}"))
    return rows


