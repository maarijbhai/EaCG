#!/usr/bin/env python3
"""Score a photograph of a printed ecg-image-kit sheet against PTB-XL.

The real-photograph experiment for the sheets `make_kit_target.py` writes.
Every earlier fidelity figure in this repository is either closed-loop (the
image was drawn by the code that decodes it) or has no waveform behind it
(the 2026-09-21 photographs are of `ecg00001.png`, a scan with no signal).
A kit sheet printed from a fold-10 PTB-XL record has both a waveform and the
pixel position of every plotted sample, so a photograph of it can be scored
end to end *and* stage by stage.

WHAT IS SCORED: the lead II rhythm strip -- the one region of a 3x4 sheet
that is a single continuous 10 s trace. Two passes per photograph, and they
answer different questions:

  known     The photograph is warped onto the sheet's own pixel grid using
            the four clicked corners and the sheet's printed size, and the
            strip is cropped where the kit says it is. Scale and crop are
            therefore handed over, and what is left is FR5 and FR6 on real
            ink: binarisation, the centroid, and the amplitude they recover.
            Also reports the trace's position error in millimetres against
            `plotted_pixels`, which needs no calibration at all.

  pipeline  The photograph is warped to a rectangle whose size comes from
            the photograph's own edge lengths -- never from the sheet's true
            aspect, which would hand the estimator half its answer (the same
            rule as `score_photo.rectify`). Then `segment.locate_rhythm_strip`
            finds the strip, and the strip is calibrated three ways, each
            scored separately:
              grid      shipped `estimate_grid_pitch` on the whole sheet
              comb      5 mm comb on the trace-free paper above the first row
              duration  the 10 s anchor: recording width / (px_per_mm * 25)
            The true px/mm in this frame is known from the sheet's size, so
            every calibration's error is reported beside its PCC.

What this still does NOT do is FR1: the four corners are clicked by a human
and then moved onto the sheet's edges by `page.refine_corners` (disable with
--no-refine). Every row is "the downstream chain on real ink, given a page
crop". `corners_clicked` and `corners` record exactly which crop.

USAGE

    # register a photograph (once), clicking the four sheet corners
    python score_kit_photo.py --add 20261001_101500.jpg \\
        --target ptbxl9_kit_500hz_300dpi --pick

    # score everything registered -> results/kitphoto/score.csv
    python score_kit_photo.py

    # self-test on simulated photographs -> results/kitphoto/selftest.csv
    python score_kit_photo.py --simulate

Photographs live in `data/kit_photos/` (gitignored, like `data/a30_pics/`);
the corners live in `kit_photos.json`, committed, so the CSV can be
regenerated by anyone holding the images. Click the corners of the PRINTED
IMAGE -- where the pink grid ends and white paper begins -- in the order
top-left, top-right, bottom-right, bottom-left, as the page lies in the
photograph after EXIF rotation.
"""

