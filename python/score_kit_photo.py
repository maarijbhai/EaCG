#: Page size the sheet is printed onto in the simulation.
SIM_PAGE_MM = (297.0, 210.0)

#: Simulated camera conditions, one photograph each. Deliberately mild to
#: moderate: this checks that the TOOLING recovers a known answer, not how
#: bad a photograph can get. `corner_noise_px` perturbs the corners handed
#: to the scorer, standing in for a human's clicking error.
SIM_CONDITIONS = (
    dict(tag="square", tilt_deg=0.0, keystone=0.00, rot_deg=0.0, blur=0.6,
         light=0.00, noise=1.0, jpeg=95, corner_noise_px=0.0),
    dict(tag="mild", tilt_deg=0.0, keystone=0.03, rot_deg=1.0, blur=0.8,
         light=0.15, noise=2.0, jpeg=90, corner_noise_px=0.0),
    dict(tag="mild_clicked", tilt_deg=0.0, keystone=0.03, rot_deg=1.0,
         blur=0.8, light=0.15, noise=2.0, jpeg=90, corner_noise_px=3.0),
    dict(tag="mild_sloppy", tilt_deg=0.0, keystone=0.03, rot_deg=1.0,
         blur=0.8, light=0.15, noise=2.0, jpeg=90, corner_noise_px=8.0),
    dict(tag="oblique", tilt_deg=0.0, keystone=0.08, rot_deg=-2.0, blur=1.1,
         light=0.25, noise=3.0, jpeg=85, corner_noise_px=0.0),
)


def simulate(target: Target, cond: dict, frame=(4000, 3000), seed: int = 0
             ) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """A camera-like image of the printed sheet. Returns (jpeg-decoded
    photo, true sheet corners, corners as a human would click them)."""
    rng = np.random.default_rng(seed)
    mm = target.px_per_mm
    sh, sw = target.sheet.shape[:2]
    pw, ph = int(round(SIM_PAGE_MM[0] * mm)), int(round(SIM_PAGE_MM[1] * mm))
    paper = np.array((238, 242, 244), np.float32)
    page = np.empty((ph, pw, 3), np.float32)
    page[:] = paper
    ox, oy = (pw - sw) // 2, (ph - sh) // 2
    # Ink is subtractive: a printer puts nothing down for white, so the
    # sheet's white IS the paper. Pasting the sheet's 255 over a greyer page
    # would print a white rectangle no printer can make, and give the
    # corner refiner an edge that a real print does not have.
    page[oy:oy + sh, ox:ox + sw] = paper * (target.sheet.astype(np.float32) / 255.0)
    page = np.clip(page, 0, 255).astype(np.uint8)

    fw, fh = frame
    scale = 0.85 * min(fw / pw, fh / ph)
    cx, cy = fw / 2.0, fh / 2.0
    a = np.deg2rad(cond["rot_deg"])
    ca, sa = np.cos(a), np.sin(a)
    k = cond["keystone"]
    # Page corners in the frame: rotate, scale, then pull the top edge in
    # by the keystone fraction -- the camera leaning back from the page.
    src = np.array([[0, 0], [pw, 0], [pw, ph], [0, ph]], np.float64) - [pw / 2, ph / 2]
    src[:2, 0] *= (1.0 - k)
    dst = np.stack([ca * src[:, 0] - sa * src[:, 1],
                    sa * src[:, 0] + ca * src[:, 1]], 1) * scale + [cx, cy]
    page_quad = np.array([[-0.5, -0.5], [pw - 0.5, -0.5], [pw - 0.5, ph - 0.5],
                          [-0.5, ph - 0.5]], np.float32)
    m = cv2.getPerspectiveTransform(page_quad, dst.astype(np.float32))
    img = cv2.warpPerspective(page, m, (fw, fh), flags=cv2.INTER_AREA
                              if scale < 1 else cv2.INTER_CUBIC,
                              borderValue=(95, 110, 125))

    sheet_quad = np.array([[ox - 0.5, oy - 0.5], [ox + sw - 0.5, oy - 0.5],
                           [ox + sw - 0.5, oy + sh - 0.5],
                           [ox - 0.5, oy + sh - 0.5]], np.float32)
    corners = cv2.perspectiveTransform(sheet_quad[None], m)[0]

    img = img.astype(np.float32)
    if cond["light"]:
        yy, xx = np.mgrid[0:fh, 0:fw].astype(np.float32)
        g = 1.0 - cond["light"] * (0.6 * xx / fw + 0.4 * yy / fh)
        img *= g[..., None]
        img[..., 0] *= 0.97          # a slightly warm cast
    if cond["blur"]:
        img = cv2.GaussianBlur(img, (0, 0), cond["blur"])
    if cond["noise"]:
        img += rng.normal(0, cond["noise"], img.shape).astype(np.float32)
    img = np.clip(img, 0, 255).astype(np.uint8)
    ok, buf = cv2.imencode(".jpg", img, [cv2.IMWRITE_JPEG_QUALITY, cond["jpeg"]])
    photo = cv2.imdecode(buf, cv2.IMREAD_COLOR)
    clicked = corners + rng.normal(0, cond["corner_noise_px"], corners.shape) \
        if cond["corner_noise_px"] else corners.copy()
    return photo, corners, clicked.astype(np.float32)


def run_simulation(target_names: list[str], refine: bool = True) -> list[dict]:
    SIM.mkdir(parents=True, exist_ok=True)
    rows = []
    for ti, name in enumerate(target_names):
        target = Target(name)
        for ci, cond in enumerate(SIM_CONDITIONS):
            photo, true, clicked = simulate(target, cond, seed=100 * ti + ci)
            stem = f"{name}__sim_{cond['tag']}"
            cv2.imwrite(str(SIM / f"{stem}.jpg"), photo,
                        [cv2.IMWRITE_JPEG_QUALITY, 100])
            entry = {"target": name, "corners_px": clicked.tolist(),
                     "file": f"{stem}.jpg",
                     "note": ";".join(f"{k}={v}" for k, v in cond.items())}
            print(f"  {stem}")
            for ref in ((False, True) if refine else (False,)):
                rows += score_photo_entry(stem, entry, SIM, TARGETS,
                                          DIAG / "sim", refine=ref,
                                          true_corners=true)
    return rows


