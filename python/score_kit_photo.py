def load_registry() -> dict:
    if REGISTRY.exists():
        return json.loads(REGISTRY.read_text("utf-8"))
    return {
        "_what": "Photographs of printed make_kit_target.py sheets, and the "
                 "four sheet corners clicked in each.",
        "_why": "FR1 (page detection) does not exist; these corners stand in "
                "for it. Corners are of the PRINTED IMAGE (where the grid "
                "meets white paper), TL TR BR BL, in the photograph's pixels "
                "after EXIF rotation. Rough clicks are fine: "
                "page.refine_corners moves them onto the sheet edges. The "
                "photographs live in data/kit_photos/ and are not committed.",
        "photos": {},
    }


def persist(name: str, rows: list[dict], params: dict) -> Path:
    RESULTS.mkdir(parents=True, exist_ok=True)
    path = RESULTS / f"{name}.csv"
    keys = list(dict.fromkeys(k for r in rows for k in r))
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)
    meta = rp.provenance(name, params)
    meta["generated_by"] = "python/score_kit_photo.py"
    meta["caveat"] = (
        "FR1 does not exist: the sheet corners were clicked by a human (or, "
        "for selftest, generated). 'known' rows hand the tracer the true "
        "scale and crop; 'pipeline' rows use segment.locate_rhythm_strip and "
        "the calibration named in the row. Truth is the PTB-XL record the "
        "sheet was printed from, lead II, 500 Hz.")
    meta["n_rows"] = len(rows)
    (RESULTS / f"{name}.json").write_text(json.dumps(meta, indent=2), "utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--add", type=str, default=None,
                   help="register a photograph in data/kit_photos/")
    p.add_argument("--target", type=str, default=None,
                   help="the kit target it shows, e.g. ptbxl9_kit_500hz_300dpi")
    p.add_argument("--corners", type=str, default=None,
                   help="'x,y x,y x,y x,y', TL TR BR BL")
    p.add_argument("--pick", action="store_true",
                   help="click the corners in a window instead")
    p.add_argument("--note", type=str, default="")
    p.add_argument("--simulate", action="store_true",
                   help="self-test on simulated photographs of every target")
    p.add_argument("--no-diagnostics", action="store_true")
    p.add_argument("--no-refine", action="store_true",
                   help="use the clicked corners as they are")
    args = p.parse_args(argv)

    if args.add:
        if not args.target:
            p.error("--add needs --target")
        path = PHOTOS / args.add
        if not path.exists():
            p.error(f"{path} not found; put the photograph in {PHOTOS}")
        Target(args.target)                       # fail early if absent
        photo = rp.read_oriented(path)
        corners = (parse_corners(args.corners) if args.corners
                   else pick_corners(photo) if args.pick else None)
        if corners is None:
            p.error("--add needs --corners or --pick")
        reg = load_registry()
        reg["photos"][path.stem] = {"file": path.name, "target": args.target,
                                    "corners_px": [[round(float(x), 1),
                                                    round(float(y), 1)]
                                                   for x, y in corners],
                                    "note": args.note}
        REGISTRY.write_text(json.dumps(reg, indent=2) + "\n", "utf-8")
        print(f"registered {path.stem} -> {args.target} in {REGISTRY.name}")
        return 0

    diag = None if args.no_diagnostics else DIAG
    if args.simulate:
        names = sorted(d.name for d in TARGETS.glob("ptbxl*_kit_*") if d.is_dir())
        if not names:
            print(f"no kit targets in {TARGETS}")
            return 2
        rows = run_simulation(names, refine=not args.no_refine)
        out = persist("selftest", rows, {"targets": names,
                                         "conditions": list(SIM_CONDITIONS)})
    else:
        reg = load_registry()
        if not reg["photos"]:
            print(f"no photographs registered in {REGISTRY.name}; "
                  f"use --add PHOTO --target NAME --pick")
            return 2
        rows = []
        for stem, entry in reg["photos"].items():
            print(f"  {stem}")
            rows += score_photo_entry(stem, entry, PHOTOS, TARGETS, diag,
                                      refine=not args.no_refine)
        out = persist("score", rows, {"registry": REGISTRY.name})
    print(f"{len(rows)} rows -> {out.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
