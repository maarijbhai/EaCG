def warp_to_sheet(photo: np.ndarray, corners: np.ndarray,
                  target: Target) -> np.ndarray:
    """Warp the clicked quad onto the sheet's own pixel grid.

    Corners are the physical corners of the printed image, i.e. the outer
    edges of its edge pixels, so they map to -0.5 and size-0.5 in pixel-
    centre coordinates rather than to 0 and size-1.
    """
    h, w = target.sheet.shape[:2]
    dst = np.array([[-0.5, -0.5], [w - 0.5, -0.5], [w - 0.5, h - 0.5],
                    [-0.5, h - 0.5]], dtype=np.float32)
    m = cv2.getPerspectiveTransform(corners.astype(np.float32), dst)
    return cv2.warpPerspective(photo, m, (w, h), flags=cv2.INTER_CUBIC,
                               borderMode=cv2.BORDER_REPLICATE)


def paper_band(sheet: np.ndarray, loc: segment.StripLocation
               ) -> tuple[int, int]:
    """Rows above the first trace row that carry grid and nothing else."""
    h = sheet.shape[0]
    first = loc.row_peaks[0]
    half_gap = (loc.row_peaks[1] - loc.row_peaks[0]) / 2.0
    y0 = int(h * segment.EDGE_FRACTION)
    y1 = int(first - half_gap)
    return y0, max(y0, y1)


