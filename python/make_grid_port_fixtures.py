#!/usr/bin/env python3
"""Golden vectors for the Kotlin port of the grid fit (GridFit.kt).

`ecgproto/gridfit.py` on a REAL photograph, ptbxl9_20261005_01 -- the one
the phone lost to locate's 3x3 opening -- at the phone's 3,200 px decode
with its automatic corners, i.e. exactly what the app will run.

The JVM tests cannot run OpenCV, and the rectified page is too large to
ship, so the band PROFILES (the only image-sized step: per band, the median
of the redness response over the band's rows) ship as inputs and every step
after them is checked: peak finding with prominences, the off-pitch filter
and indexing, chaining between bands, the reweighted homography and the
regular page's placement. Decisions must match exactly; reals to 1e-6
relative. The profile step itself is checked on a small procedural image
both sides define the same way.

    python make_grid_port_fixtures.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import cv2
import numpy as np
from scipy import signal as sps

sys.path.insert(0, str(Path(__file__).resolve().parent))

import run_photo as rp  # noqa: E402
import score_kit_photo as skp  # noqa: E402
from ecgproto import gridfit as G, page, segment, sheet  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "android" / "app" / "src" / "test" / "resources" / "grid_port_fixtures.txt"
PHOTO = "ptbxl9_20261005_01"
PHONE_MAX_DIM = 3200


def fmt(v) -> str:
    v = float(v)
    return "NaN" if not np.isfinite(v) else repr(v)


def row(name, vals) -> str:
    return name + " " + " ".join(fmt(v) for v in vals)


def fake_rgb(h, w):
    """Shared with GridPortFixturesTest: BGR uint8, (h, w, 3)."""
    y, x = np.mgrid[0:h, 0:w]
    b = (x * 7 + y * 3) % 256
    g = (x * 5 + y * 11) % 256
    r = (x * 13 + y * 2 + (x // 9) * 40) % 256
    return np.stack([b, g, r], -1).astype(np.uint8)


def main() -> int:
    lines = ["# generated by python/make_grid_port_fixtures.py -- do not edit",
             f"# golden vectors for GridFit.kt from {PHOTO} at {PHONE_MAX_DIM} px"]
    for k in ("PITCH_MM", "BAND_MM", "BAND_STEP_MM", "EDGE_MARGIN_MM", "MIN_REL_PROMINENCE",
              "ON_PITCH_FRACTION", "MATCH_FRACTION", "HUBER_PX", "MIN_RULES"):
        lines.append(f"const.{k} {fmt(getattr(G, k))}")

    # ---- the profile step on a procedural image ---------------------------
    fh, fw = 120, 90
    fake = fake_rgb(fh, fw)
    fresp = G.redness(fake)
    lines.append(row("fake.redness.sum", [fresp.sum()]))
    for axis in (0, 1):
        c, profs, m = G.band_profiles(fresp, 25.0, axis)          # 5 px/mm
        lines.append(f"fake.{axis}.margin {m}")
        lines.append(row(f"fake.{axis}.centres", c))
        for i, p in enumerate(profs):
            lines.append(row(f"fake.{axis}.prof.{i}", p))

    # ---- the real page -----------------------------------------------------
    e = skp.load_registry()["photos"][PHOTO]
    photo = rp.read_oriented(skp.PHOTOS / e["file"])
    s = PHONE_MAX_DIM / max(photo.shape[:2])
    photo = cv2.resize(photo, None, fx=s, fy=s, interpolation=cv2.INTER_AREA)
    fc = page.find_sheet_corners(photo)
    rect, _ = sheet.rectify(photo, fc.corners)
    guess = segment.locate_sheet(rect).anchor_px_per_mm
    resp = G.redness(rect)
    h, w = resp.shape
    lines.append(f"rect.shape {h} {w}")
    lines.append(row("guess", [guess]))

    # Pitch refinement: the middle third's profile -> peaks -> median gap.
    pitch0 = G.PITCH_MM * guess
    mid = np.median(resp[h // 3: 2 * h // 3], axis=0)
    lines.append(row("mid.prof", mid))
    pk = G._band_peaks(mid, pitch0)
    lines.append(row("mid.peaks", pk))
    fit = G.fit_grid(rect, guess)
    pitch = fit.px_per_mm * G.PITCH_MM
    lines.append(row("pitch", [pitch]))

    # find_peaks itself, on the first vertical band, before any filtering.
    for axis in (0, 1):
        centres, profs, margin = G.band_profiles(resp, pitch, axis)
        lines.append(f"axis{axis}.margin {margin}")
        lines.append(f"axis{axis}.nbands {len(profs)}")
        lines.append(row(f"axis{axis}.centres", centres))
        bands = []
        for i, prof in enumerate(profs):
            lines.append(row(f"axis{axis}.prof.{i}", prof))
            if i == 0:
                k = int(round(pitch)) | 1
                p = prof - cv2.blur(prof.reshape(1, -1).astype(np.float32), (k, 1))[0]
                lines.append(row(f"axis{axis}.detrended.0", p))
                raw = G._peaks_by_distance(p, max(2, int(0.6 * pitch)))
                lines.append(row(f"axis{axis}.findpeaks.0", raw))
                lines.append(row(f"axis{axis}.prominences.0", sps.peak_prominences(p, raw)[0]))
            peaks = G._band_peaks(prof, pitch)
            lines.append(row(f"axis{axis}.peaks.{i}", peaks))
            xs, idx = G._index_band(peaks + margin, pitch)
            lines.append(row(f"axis{axis}.kept.{i}", xs))
            lines.append(row(f"axis{axis}.idx.{i}", idx))
            bands.append((centres[i], xs, idx))
        mid_b = len(bands) // 2
        offsets = {mid_b: 0}
        for order in (range(mid_b + 1, len(bands)), range(mid_b - 1, -1, -1)):
            for b in order:
                prev = b - 1 if b > mid_b else b + 1
                off = G._chain(bands[prev], bands[b], offsets[prev], pitch)
                if off is None:
                    break
                offsets[b] = off
        lines.append(f"axis{axis}.offsets " + " ".join(
            f"{b} {offsets[b]}" for b in sorted(offsets)))
        sam = G._rule_samples(resp, pitch, axis)
        lines.append(f"axis{axis}.samples.n {len(sam)}")
        lines.append(row(f"axis{axis}.samples.sum", sam.sum(axis=0)))

    lines.append(row("fit.H", fit.H.ravel()))
    lines.append(f"fit.size {fit.out_size[0]} {fit.out_size[1]}")
    lines.append(row("fit.px_per_mm", [fit.px_per_mm]))
    lines.append(row("fit.rms_mm", [fit.rms_mm]))
    lines.append(f"fit.rules {fit.n_vertical} {fit.n_horizontal}")
    lines.append(f"fit.samples {fit.n_samples}")
    lines.append(row("fit.inliers", [fit.inlier_fraction]))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({OUT.stat().st_size / 1e6:.1f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
