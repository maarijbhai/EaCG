#!/usr/bin/env python3
"""Golden vectors for ClfInput.kt: the classifier's input from a digitised sheet.

`ecgproto.clf_input.from_columns` is the reference; the phone must hand the
classifier the same 1,000 x 13 numbers. Two cases:

  real   a phone export (PTB-XL 9, 2026-10-05, learned tracer) -- the real
         layout, NaN outside every cell, a NaN at the very first sample;
  synth  the edges: blocks partly and wholly NaN, a lead missing entirely,
         a window with an even number of finite blocks (median = mean of the
         middle two), a rhythm strip two samples short.

Writes android/app/src/test/resources/clf_port_fixtures.txt:

    case <name>
    col <lead> v v ... (5,000 values, 'nan' for NaN)
    expect v v ... (13,000 values, row-major: sample t, channel c at t*13+c)

    python make_clf_port_fixtures.py        (from python/)
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import score_device_sheets as SDS  # noqa: E402
from ecgproto import clf_input as C  # noqa: E402

OUT = HERE.parent / "android" / "app" / "src" / "test" / "resources" / "clf_port_fixtures.txt"
REAL = HERE.parent / "data" / "device_exports" / "eacg_sheet_ptbxl9_kit_500hz_300dpi_model_20261005_122715.csv"


def fmt(v: float) -> str:
    return "nan" if not np.isfinite(v) else repr(float(v))


def synth() -> dict:
    rng = np.random.default_rng(7)
    cols = {}
    for lead, col in C.PRINTED_COLUMN.items():
        name = C.LEADS[lead]
        if name == "V3":
            continue                                       # a lead missing entirely
        c = np.full(5000, np.nan)
        c[col * 1250:(col + 1) * 1250] = rng.normal(0.4 * lead, 0.3, 1250)
        cols[name] = c
    cols["I"][2:4] = np.nan                                # a block partly NaN
    cols["I"][5:10] = np.nan                               # a block wholly NaN -> 249 finite (odd)
    cols["aVL"][1250:1255] = np.nan                        # -> 249 finite
    cols["aVL"][1300:1305] = np.nan                        # -> 248 finite: even median
    cols["II_rhythm"] = rng.normal(0.0, 0.5, 4998)         # two samples short
    return cols


def main() -> int:
    if not REAL.exists():
        print(f"missing {REAL} (data/ is not committed; the fixture needs it)")
        return 1
    _, real = SDS.read_export(REAL)
    real = {k: v for k, v in real.items() if k != "time_s"}
    lines = ["# generated by python/make_clf_port_fixtures.py from ecgproto.clf_input.from_columns"]
    for name, cols in (("real", real), ("synth", synth())):
        x = C.from_columns(cols)
        lines.append(f"case {name}")
        for k, v in cols.items():
            lines.append(f"col {k} " + " ".join(fmt(a) for a in v))
        lines.append("expect " + " ".join(fmt(a) for a in x.astype(np.float64).ravel()))
        print(f"{name}: {len(cols)} columns, input non-zero {int((x != 0).sum())} of {x.size}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size / 1e3:.0f} kB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
