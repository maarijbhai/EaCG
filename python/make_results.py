#!/usr/bin/env python3
"""Regenerate every result of the photo experiment, organised by set. ONE command.

    python make_results.py            (from python/; commit the code and python/test_set.csv first)

1. score_device_sheets.py   every phone export -> results/device/sheet_scores.csv
2. make_report_figures.py   per set, and the comparison
3. make_stats_workbook.py   per set, and the comparison
into

    results/report/set_A_clean/    set A: the 12 printed sheets as clean images
    results/report/set_B_ideal/    set B: the 24 ideal photographs
    results/report/compare_sets/   A against B (and the robustness set, once it has photos)

and writes results/report/README.md describing every file. Old flat files in
results/report/ (from before 2026-10-14) are removed.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(HERE))

import make_report_figures as R  # noqa: E402
import make_stats_workbook as W  # noqa: E402
import score_device_sheets as SDS  # noqa: E402

REPORT = REPO / "results" / "report"
FOLDERS = {
    "set_A_clean": (["clean"], "stats_set_A.xlsx"),
    "set_B_ideal": (["ideal"], "stats_set_B.xlsx"),
    "compare_sets": (None, "stats_compare_sets.xlsx"),
}

README = """# Results of the photo experiment

Regenerated by `python python/make_results.py` from `results/device/sheet_scores.csv`
(every phone export, scored against its PTB-XL truth) and the manifest `python/test_set.csv`.
Every file has a `.json` sidecar with the git commit it was made from.

| Folder | What |
|---|---|
| `set_A_clean/` | **Set A**: the 12 printed test sheets as clean digital images (no camera), learned and classical tracer |
| `set_B_ideal/` | **Set B**: the same 12 sheets photographed in good light, 2 photos each (24), both tracers |
| `compare_sets/` | **A against B** (and the robustness set once it has photos) |

## In each set folder

| File | What it shows |
|---|---|
| `stats_set_*.xlsx` | Everything, for looking: README of every method, summaries, per photo, per sheet, per lead, timing and memory, photo quality (B) |
| `fidelity_<set>.tex/.csv` | **Table**: every measure, median [IQR], learned vs classical, Wilcoxon |
| `on_device.tex/.csv` | **Table**: time and peak memory per pipeline stage on the A30s (learned) |
| `example_<set>_learned.pdf`, `..._classical.pdf` | **Figure**: the lead whose learned PCC is the set's median, digitised over the truth |
| `pcc_by_lead.pdf/.csv` | **Figure**: PCC per lead name (I ... V6), median and IQR |
| `plain_vs_aligned.pdf/.csv` | **Figure**: PCC as cut against PCC with perfect timing (learned) |
| `pcc_by_quality.pdf/.csv` | **Figure**: PCC by the app's quality verdict (learned) |
| `latency_stages.pdf/.csv` | **Figure**: time per stage, both tracers |
| `headline.json` | The headline numbers |

## In `compare_sets/`

| File | What it shows |
|---|---|
| `stats_compare_sets.xlsx` | Both sets, plus A vs B per measure, per sheet and per lead (B minus A) |
| `compare_sets.tex/.csv` | **Table**: every measure for A and B side by side, and B minus A with a 95% CI |
| `pcc_by_set.pdf/.csv` | **Figure**: PCC per set (and robustness condition), both tracers |
| `fidelity_clean.tex`, `fidelity_ideal.tex` | Each set's fidelity table, as in the set folders |
| `headline.json` | The headline numbers of both sets |
"""


def main() -> int:
    # An .xlsx open in Excel cannot be replaced (Windows locks it; Excel leaves
    # a '~$' file beside it): stop before anything is removed or rewritten.
    locked = sorted(p.name[2:] for p in REPORT.rglob("~$*"))
    if locked:
        print("Close these in Excel first, then run again:", ", ".join(locked))
        return 1
    SDS.main()
    for p in REPORT.iterdir():                      # the old flat layout
        if p.is_file():
            p.unlink()
    for folder, (sets, book) in FOLDERS.items():
        d = REPORT / folder
        if d.exists():
            shutil.rmtree(d)
        argv = ["--out", str(d.relative_to(REPO))] + (["--sets", *sets] if sets else [])
        R.main(argv)
        W.main((["--sets", *sets] if sets else []) + ["--out", str((d / book).relative_to(REPO))])
    (REPORT / "README.md").write_text(README, encoding="utf-8", newline="\n")
    print("wrote", REPORT / "README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
